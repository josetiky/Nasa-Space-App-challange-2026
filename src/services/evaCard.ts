import { EVA } from "@/core/science/constants";
import { gcrDosePerSol, pressureAt } from "@/core/science/environment";
import { arrivalMinutes, sampleWalk, type WalkTimeline } from "@/core/science/evaWalk";
import type { RoverEvaResult, TraverseStop } from "@/core/science/roverTraverse";

/**
 * EVA "cuff card" (Apollo crews wore their timeline on the wrist): a Markdown sheet with the walk's
 * timeline, consumables and hazards, built from the same plan and timeline the app shows.
 */

const SOL_MINUTES = 24.6597 * 60;

/** Mission elapsed time as h:mm, rounded to the minute. */
export function formatMissionTime(minutes: number): string {
  const total = Math.max(0, Math.round(minutes));
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
}

const metres = (m: number) => `${Math.round(m).toLocaleString("en-US")} m`;

export interface EvaCardInput {
  result: RoverEvaResult;
  timeline: WalkTimeline;
  crew: number;
  returnToStart: boolean;
  /** Every stop of the traverse, so numbers match the map. */
  allStops: TraverseStop[];
  /** Credit line for the rover data. */
  credit: string;
}

export interface Milestone {
  /** Mission minutes since the start of the EVA. */
  t: number;
  event: string;
}

/** Start, each science stop (on arrival), the turn-around or end, and the return — in time order. */
export function evaMilestones(
  result: RoverEvaResult,
  timeline: WalkTimeline,
  returnToStart: boolean,
  allStops: TraverseStop[],
): Milestone[] {
  const { outbound } = result;
  const stopBySol = new Map(result.stops.map((s) => [s.sol, s]));
  const roundTrip = returnToStart && outbound.length > 1;
  const rows: Milestone[] = [{ t: 0, event: `Start at sol ${outbound[0]!.sol}` }];
  outbound.forEach((w, k) => {
    const arrive = arrivalMinutes(timeline, k);
    const stop = stopBySol.get(w.sol);
    if (stop)
      rows.push({
        t: arrive,
        event: `Stop ${allStops.indexOf(stop) + 1} · ${stop.title} (${EVA.stopMinutes} min)`,
      });
    if (k > 0 && k === outbound.length - 1)
      rows.push({
        t: arrive + (stop ? EVA.stopMinutes : 0),
        event: roundTrip ? `Turn-around at sol ${w.sol}` : `End at sol ${w.sol}`,
      });
  });
  if (roundTrip) rows.push({ t: timeline.totalMinutes, event: "Back at start" });
  return rows;
}

export function buildEvaCard({
  result,
  timeline,
  crew,
  returnToStart,
  allStops,
  credit,
}: EvaCardInput): string {
  const { plan, outbound } = result;
  const first = outbound[0]!;
  const last = outbound[outbound.length - 1]!;
  const stopBySol = new Map(result.stops.map((s) => [s.sol, s]));
  const label = (sol: number) => {
    const stop = stopBySol.get(sol);
    return stop ? ` (${stop.title})` : "";
  };
  const roundTrip = returnToStart && outbound.length > 1;
  const rows = evaMilestones(result, timeline, returnToStart, allStops);

  const meanElevation = outbound.reduce((sum, w) => sum + w.elevationM, 0) / outbound.length;
  const doseUsv =
    gcrDosePerSol(pressureAt(meanElevation)) * (plan.durationMin / SOL_MINUTES) * 1000;

  const lines = [
    `# EVA card — ${plan.siteName}`,
    "",
    `Route: sol ${first.sol}${label(first.sol)} → sol ${last.sol}${label(last.sol)}${roundTrip ? ", back to start" : ", one way"} · crew ${crew}`,
    `Totals (MODELLED): ${metres(plan.distanceM)} walked · duration ${formatMissionTime(plan.durationMin)} (h:mm) · ${plan.o2Kg.toFixed(2)} kg suit O₂ for the crew · ${plan.elevationGainM.toFixed(1)} m climb · ~${doseUsv.toFixed(0)} µSv cosmic-ray dose (surface rate, no suit shielding)`,
    `Curiosity drove ${metres(result.odometryM)} over the same span (one way); highest rover tilt at a stop: ${result.maxTiltDeg.toFixed(1)}°.`,
    "",
    "| T+ | Event | Walked | O₂ used |",
    "| --- | --- | ---: | ---: |",
    ...rows.map(({ t, event }) => {
      const state = sampleWalk(timeline, t);
      return `| ${formatMissionTime(t)} | ${event} | ${metres(state.distanceM)} | ${state.o2Kg.toFixed(2)} kg |`;
    }),
    "",
    "## Hazards",
    ...(plan.hazards.length
      ? plan.hazards.map((h) => `- ${h}`)
      : [`- None at or above the ${EVA.cautionSlopeDeg}° caution threshold.`]),
    "",
    "## Science stops",
    ...result.stops.map((s) => {
      const links = [s.source, ...(s.alsoSee ?? [])]
        .map((l) => `[${l.label}](${l.url})`)
        .join(" · ");
      return `- **Stop ${allStops.indexOf(s) + 1} · ${s.title}** (sol ${s.sol}): ${s.text} Source: ${links}`;
    }),
    "",
    "---",
    `Rover positions, elevations, tilt and odometry: ${credit}. Walking time, O₂ and dose are MODELLED with the MARS // SURVIVE suit and environment models (docs/SIMULATION_MODEL.md).`,
    "Generated by MARS // SURVIVE — Intelligent Mission Control (NASA Space Apps 2026).",
    "",
  ];
  return lines.join("\n");
}
